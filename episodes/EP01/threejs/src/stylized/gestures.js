// Named gestures as additive local rotations and IK windows.
// Keys are [time, pitchX, yawY, rollZ] in the bone's local frame:
// +X pitches forward / nods down, +Y yaws toward character-left, +Z rolls.
// Timing is anticipation, then the action, then settle. The head keys start
// later than the hands, and the hands start later than the spine.

const E = (t, x = 0, y = 0, z = 0) => [t, x, y, z];

function ik(hand, near, keys, hold = false) {
  return {
    hand,
    near,
    hold,
    keys: keys.map(([t, offset, w]) => ({ t, near, offset, w })),
  };
}

function define(name, dur, tracks, extra = {}) {
  return {
    name,
    dur,
    tracks,
    hold: !!extra.hold,
    side: extra.side || null,
    pose: extra.pose || null,
    hands: extra.hands || null,
    ik: extra.ik || [],
  };
}

